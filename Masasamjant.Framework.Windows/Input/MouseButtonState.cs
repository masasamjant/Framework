namespace Masasamjant.Windows.Input
{
    /// <summary>
    /// Defines state of mouse button.
    /// </summary>
    public enum MouseButtonState : int
    {
        /// <summary>
        /// Mouse button was pressed down.
        /// </summary>
        Down = 0,

        /// <summary>
        /// Mouse button was released.
        /// </summary>
        Up = 1
    }
}
