namespace Masasamjant.Windows.WinApi
{
    internal static class Messages
    {
        /// <summary>
        /// Posted when left mouse button is pressed down.
        /// </summary>
        internal const int WM_LBUTTONDOWN = 0x0201;

        /// <summary>
        /// Posted when left mouse button is released up.
        /// </summary>
        internal const int WM_LBUTTONUP = 0x0202;

        /// <summary>
        /// Posted when mouse move.
        /// </summary>
        internal const int WM_MOUSEMOVE = 0x0200;

        /// <summary>
        /// Posted when mouse wheel is scrolled.
        /// </summary>
        internal const int WM_MOUSEWHEEL = 0x020A;

        /// <summary>
        /// Posted when right mouse button is pressed down.
        /// </summary>
        internal const int WM_RBUTTONDOWN = 0x0204;

        /// <summary>
        /// Posted when right mouse button is released up.
        /// </summary>
        internal const int WM_RBUTTONUP = 0x0205;

        /// <summary>
        /// Posted when middle mouse button is pressed down.
        /// </summary>
        internal const int WM_MBUTTONDOWN = 0x0207;

        /// <summary>
        /// Posted when middle mouse button is released up.
        /// </summary>
        internal const int WM_MBUTTONUP = 0x0208;

        /// <summary>
        /// Posted when X mouse button is pressed down.
        /// </summary>
        internal const int WM_XBUTTONDOWN = 0x020B;

        /// <summary>
        /// Posted when X mouse button is released up.
        /// </summary>
        internal const int WM_XBUTTONUP = 0x020C;
    }
}
