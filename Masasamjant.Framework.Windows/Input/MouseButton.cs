namespace Masasamjant.Windows.Input
{
    /// <summary>
    /// Defines mouse buttons.
    /// </summary>
    public enum MouseButton : int
    {
        /// <summary>
        /// None
        /// </summary>
        None = 0,

        /// <summary>
        /// Left button.
        /// </summary>
        Left = 1,

        /// <summary>
        /// Middle button.
        /// </summary>
        Middle = 2,

        /// <summary>
        /// Right button.
        /// </summary>
        Right = 3,

        /// <summary>
        /// X1 button.
        /// </summary>
        XButton1 = 4,

        /// <summary>
        /// X2 button.
        /// </summary>
        XButton2 = 5
    }
}
